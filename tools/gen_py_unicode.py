"""Sinh src/ThreadsToxic.Web/Services/Export/PyUnicode.g.cs: các bảng Unicode của Python mà .NET không có.

Bản port bộ lọc tiếng Việt (VietText.cs) phải cho kết quả giống hệt crawler (Python). Phần lớn tính chất
Unicode lấy thẳng từ .NET (category khớp với Python khi cùng phiên bản Unicode), riêng các phần sau
.NET không có hoặc khác Python nên được sinh ra ở đây:
- str.lower() và str.casefold() (ánh xạ đầy đủ, khác Rune.ToLowerInvariant ở vài chục ký tự).
- Chữ cái có tên Unicode bắt đầu bằng "LATIN " (contains_foreign_script dùng unicodedata.name).
- Tập ký tự khớp với từng chữ cái trong biểu thức chính quy re.IGNORECASE của crawler.

Chạy bằng đúng phiên bản Python mà crawler dùng:
    python tools/gen_py_unicode.py
"""
import re
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src/ThreadsToxic.Web/Services/Export/PyUnicode.g.cs"

# Chữ cái xuất hiện trong các mẫu re.IGNORECASE của text_normalizer.py
IGNORECASE_LETTERS = sorted(set("Translate" "Xem bản dịch" "Dịch" "meta" "ai") - {" "})


def code_points():
    for cp in range(sys.maxunicode + 1):
        if not 0xD800 <= cp <= 0xDFFF:
            yield cp


def hexes(text):
    return " ".join(f"{ord(ch):X}" for ch in text)


def mapping_table(func, base):
    """Các mã mà func(c) khác base(c), dạng 'CP=HEX HEX;...'."""
    entries = []
    for cp in code_points():
        ch = chr(cp)
        if func(ch) != base(ch):
            entries.append(f"{cp:X}={hexes(func(ch))}")
    return ";".join(entries)


def latin_letter_ranges():
    ranges, start = [], None
    for cp in range(sys.maxunicode + 2):
        ch = chr(cp) if cp <= sys.maxunicode else ""
        ok = bool(ch) and unicodedata.category(ch).startswith("L") \
            and unicodedata.name(ch, "").startswith("LATIN ")
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            ranges.append((start, cp - 1))
            start = None
    return ranges


def ignorecase_sets():
    entries = []
    for letter in IGNORECASE_LETTERS:
        pattern = re.compile(re.escape(letter), re.IGNORECASE)
        matches = "".join(chr(cp) for cp in code_points() if pattern.fullmatch(chr(cp)))
        entries.append(f"{ord(letter):X}={hexes(matches)}")
    return ";".join(entries)


def chunk(text, size=100):
    parts = [text[i:i + size] for i in range(0, len(text), size)] or [""]
    return "\n".join(f'        "{part}"' + (" +" if i < len(parts) - 1 else ";") for i, part in enumerate(parts))


def main():
    lower = mapping_table(str.lower, lambda ch: ch)
    casefold = mapping_table(str.casefold, str.lower)
    latin = ", ".join(f"0x{a:X}, 0x{b:X}" for a, b in latin_letter_ranges())
    source = f"""// <auto-generated>
// Sinh bởi tools/gen_py_unicode.py từ Python {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Không sửa tay.
// </auto-generated>
namespace ThreadsToxic.Web.Services.Export;

internal static partial class PyUnicode
{{
    // str.lower(): mã có chữ thường khác chính nó, dạng "CP=HEX HEX;..."
    private const string LowerTable =
{chunk(lower)}

    // str.casefold(): chỉ những mã mà casefold() khác lower()
    private const string CasefoldTable =
{chunk(casefold)}

    // Chữ cái có tên Unicode bắt đầu bằng "LATIN " (từng cặp đầu, cuối)
    private static readonly int[] LatinLetterRanges = [{latin}];

    // Ký tự khớp với từng chữ cái của mẫu khi dùng re.IGNORECASE
    private const string IgnoreCaseTable =
{chunk(ignorecase_sets())}
}}
"""
    OUT.write_text(source, encoding="utf-8", newline="\n")
    print(f"Đã ghi {OUT}")


if __name__ == "__main__":
    main()
